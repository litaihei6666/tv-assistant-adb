const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const html = fs.readFileSync('index.html', 'utf8');
const js = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const items = [{dataset:{search:'tcl 65v6d'},hidden:false},{dataset:{search:'小米 redmi'},hidden:false},{dataset:{search:'hisense test-model',kind:'research'},hidden:false}];
let handler;
const query = {value:'',addEventListener:(_, fn)=>handler=fn};
const count = {textContent:''};
const research = {open:false};
const document = {getElementById: id => ({query,count,research}[id]), querySelectorAll:()=>items};
vm.runInNewContext(js,{document});
assert.equal(count.textContent,'显示 2 条已整理记录；1 条待审查机型资料');
assert.equal(research.open,false);
query.value='65V6D'; handler();
assert.equal(items[0].hidden,false); assert.equal(items[1].hidden,true);
assert.equal(count.textContent,'显示 1 条已整理记录；0 条待审查机型资料');
query.value='test-model'; handler();
assert.equal(count.textContent,'显示 0 条已整理记录；1 条待审查机型资料');
assert.equal(research.open,true);
query.value='不存在'; handler(); assert.equal(count.textContent,'显示 0 条已整理记录；0 条待审查机型资料');
console.log('Offline search interaction passed');
